"""Regenerates config/character_list.h (configurator character names) from the user's Table.dll.

  python gen_character_list.py <Table.dll> <out header>

Names are a category plus the model bank name; kinds whose body is not the 16-node humanoid skeleton are marked as
possibly invisible when played (seen in game for boss3 and the frog).
"""
import sys

import character_kinds as ck
import model_formats as mf

HUMANOID_NODES = 16
CATEGORIES = [
    (range(0, 1), "Zombie"), (range(1, 26), "Zombie"), (range(26, 32), "Creature"), (range(32, 56), "Civilian"),
    (range(56, 57), "Detective"), (range(57, 62), "Player"), (range(62, 70), "Story character"),
    (range(70, 71), "Story character"), (range(71, 86), "Boss"), (range(86, 88), "Extra"),
]


def category(kind):
    for kinds, name in CATEGORIES:
        if kind in kinds:
            return name
    return "Character"


def main():
    tables = mf.ModelTables(sys.argv[1])
    lines = ["#pragma once", "", "/* Generated by tools/gen_character_list.py; index = character kind. */",
             "static const char *const character_names[] = {"]
    for kind in range(ck.kind_count(tables)):
        parts = ck.body_parts(tables, kind)
        banks = ck.kind_banks(tables, kind)
        bank = banks.most_common(1)[0][0][:-4] if banks else "none"
        note = "" if len(parts) == HUMANOID_NODES and len(banks) == 1 else ", may be invisible"
        lines.append(f'    "{category(kind)} ({bank}{note})",')
    lines += ["};", "#define CHARACTER_COUNT ((int)(sizeof character_names / sizeof character_names[0]))", ""]
    open(sys.argv[2], "w", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    main()
