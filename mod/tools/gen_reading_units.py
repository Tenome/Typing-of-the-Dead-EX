import os

TOOLS = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(TOOLS, "reading_units.tsv")
OUTPUT = os.path.join(TOOLS, "..", "src", "reading_units.c")


def load_reading_units(path=SOURCE):
    units = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            text, unit_id = line.split("\t")
            units.append((text, int(unit_id)))
    return units


def c_wide_literal(text):
    return 'L"' + "".join(f"\\x{ord(char):04x}" for char in text) + '"'


def main():
    units = load_reading_units()
    lines = [
        "/* generated by tools/gen_reading_units.py from tools/reading_units.tsv */",
        '#include "reading_units.h"',
        "",
        "const reading_unit reading_units[] = {",
    ]
    lines += [f"    {{{c_wide_literal(text)}, {unit_id}}}, /* {text} */" for text, unit_id in units]
    lines += ["};", "", "const int reading_unit_count = sizeof reading_units / sizeof reading_units[0];", ""]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {len(units)} reading units to {os.path.normpath(OUTPUT)}")


if __name__ == "__main__":
    main()
