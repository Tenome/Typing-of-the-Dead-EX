"""Generate the word-list structure used by pack tools from the original word files.

Writes config/pack_template.c (compiled into the configurator) and tools/word_lists.tsv (for the Python tools):
for every original word list its bank (main or kids), kind (normal, quiz = first word is a question typed as '?',
special = special-mode records) and the difficulty of each slot. No game text is stored.

usage: python gen_pack_template.py extracted_word_hab_dir extracted_wordkids_hab_dir
"""
import glob
import os
import struct
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(TOOLS, "..", "config", "pack_template.c")
LISTS_OUTPUT = os.path.join(TOOLS, "word_lists.tsv")
RECORD_BYTES = 0x88
READING_SLOTS = 64
QUESTION_READING = (286,)
SPECIAL_MODE_SHIFT = 16
BANKS = ("main", "kids")


def list_kind(records):
    if records and any(group >> SPECIAL_MODE_SHIFT for group, _ in records):
        return "special"
    if records and records[0][1] == QUESTION_READING:
        return "quiz"
    return "normal"


def read_lists(folder):
    lists = []
    for path in sorted(glob.glob(os.path.join(folder, "*.bin"))):
        name = os.path.splitext(os.path.basename(path))[0]
        if name == "font":
            continue
        data = open(path, "rb").read()
        records = []
        for offset in range(0, len(data) - RECORD_BYTES + 1, RECORD_BYTES):
            group, _ = struct.unpack_from("<II", data, offset)
            if group == 0xFFFFFFFF:
                break
            units = struct.unpack_from(f"<{READING_SLOTS}H", data, offset + 8)
            units = units[: units.index(0)] if 0 in units else units
            if not units:
                break
            records.append((group, units))
        lists.append((name, list_kind(records), [group & 0xFFFF for group, _ in records]))
    return lists


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    banks = [(0, read_lists(sys.argv[1])), (1, read_lists(sys.argv[2]))]
    difficulties, entries, rows = [], [], []
    for kids, lists in banks:
        for name, kind, slots in lists:
            entries.append(f'    {{"{name}", {kids}, {int(kind != "normal")}, {len(difficulties)}, {len(slots)}}},')
            difficulties.extend(slots)
            rows.append(f"{BANKS[kids]}\t{name}\t{kind}\t{','.join(map(str, slots))}\n")
    lines = ["/* generated by tools/gen_pack_template.py: list names and slot difficulties only */",
             '#include "pack_template.h"', "", "const unsigned short template_difficulties[] = {"]
    lines += ["    " + ", ".join(map(str, difficulties[i:i + 20])) + "," for i in range(0, len(difficulties), 20)]
    lines += ["};", "", "const template_list template_lists[] = {"] + entries
    lines += ["};", "const int template_list_count = sizeof template_lists / sizeof template_lists[0];", ""]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    with open(LISTS_OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("# bank\tlist\tkind\tslot difficulties\n")
        handle.writelines(rows)
    kept = sum(1 for _, lists in banks for _, kind, _ in lists if kind != "normal")
    print(f"{len(entries)} lists ({kept} quiz/special), {len(difficulties)} slots -> {os.path.normpath(OUTPUT)}, "
          f"{os.path.normpath(LISTS_OUTPUT)}")


if __name__ == "__main__":
    main()
