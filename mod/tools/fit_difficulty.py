"""Fit the word difficulty model from the original word files and generate src/unit_costs.c.

difficulty(word) = sum of key costs over the typed keys (first spelling of each typing unit; a small tsu costs
the consonant it doubles) + a per-unit correction for units whose original spelling choice differed.

usage: python fit_difficulty.py extracted_word_hab_dir romaji_table.json
       (extract word.HAB_O with hab_tool.py extract; romaji_table.json from hab_tool.py romaji-table)
"""
import glob
import json
import os
import struct
import sys

import numpy as np

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUTPUT_C = os.path.join(TOOLS, "..", "src", "unit_costs.c")
OUTPUT_JSON = os.path.join(TOOLS, "difficulty_model.json")
RECORD_BYTES = 0x88
READING_SLOTS = 64
SMALL_TSU = 203
VOWELS = "AIUEON"
MIN_CORRECTION_SUPPORT = 3


def read_records(folder):
    readings = {}
    for path in glob.glob(os.path.join(folder, "*.bin")):
        if os.path.basename(path) == "font.bin":
            continue
        data = open(path, "rb").read()
        for offset in range(0, len(data) - RECORD_BYTES + 1, RECORD_BYTES):
            group, _ = struct.unpack_from("<II", data, offset)
            if group == 0xFFFFFFFF:
                break
            units = struct.unpack_from(f"<{READING_SLOTS}H", data, offset + 8)
            units = units[: units.index(0)] if 0 in units else units
            if not units:
                break
            if group >> 16 == 0:
                readings[tuple(units)] = group & 0xFFFF
    return readings


def first_spelling(table, unit):
    return table[str(unit)]["spellings"][0]


def doubled_consonant(table, units, index):
    if index + 1 >= len(units):
        return None
    following = first_spelling(table, units[index + 1])
    return following[0] if following and following[0].isalpha() and following[0] not in VOWELS else None


def typed_keys(table, units):
    keys = []
    for index, unit in enumerate(units):
        doubled = doubled_consonant(table, units, index) if unit == SMALL_TSU else None
        keys.append(doubled or first_spelling(table, unit))
    return "".join(keys)


def least_squares(rows, targets, columns):
    matrix = np.zeros((len(rows), len(columns)))
    position = {column: i for i, column in enumerate(columns)}
    for row_index, row in enumerate(rows):
        for item in row:
            matrix[row_index, position[item]] += 1
    weights, *_ = np.linalg.lstsq(matrix, targets, rcond=None)
    return matrix, np.round(weights)


def fit(readings, table):
    words = list(readings)
    targets = np.array([readings[w] for w in words], float)
    key_rows = [typed_keys(table, w) for w in words]
    keys = sorted(set("".join(key_rows)))
    key_matrix, key_costs = least_squares(key_rows, targets, keys)
    residual = targets - key_matrix @ key_costs
    units = sorted({u for w in words for u in w})
    unit_matrix, corrections = least_squares(words, residual, units)
    support = unit_matrix.astype(bool).sum(axis=0)
    kept = {u: int(c) for u, c, s in zip(units, corrections, support) if c and s >= MIN_CORRECTION_SUPPORT}
    predicted = key_matrix @ key_costs + unit_matrix @ np.array([kept.get(u, 0) for u in units])
    exact = float((predicted == targets).mean())
    return {k: int(c) for k, c in zip(keys, key_costs)}, kept, exact, len(words)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_c(table, key_costs, corrections):
    lines = [
        "/* generated by tools/fit_difficulty.py from the original word files */",
        '#include "unit_costs.h"',
        "",
        "const key_cost key_costs[] = {",
    ]
    lines += [f"    {{'{k}', {c}}}," if k not in "'\\" else f"    {{'\\{k}', {c}}}," for k, c in key_costs.items()]
    lines += ["};", "const int key_cost_count = sizeof key_costs / sizeof key_costs[0];", "", "const unit_cost unit_costs[] = {"]
    for unit in sorted(table, key=int):
        spellings = table[unit]["spellings"]
        if spellings:
            lines.append(f"    {{{unit}, {c_string(spellings[0])}, {corrections.get(int(unit), 0)}}},")
    lines += ["};", "const int unit_cost_count = sizeof unit_costs / sizeof unit_costs[0];", ""]
    with open(OUTPUT_C, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    table = json.load(open(sys.argv[2], encoding="utf-8"))
    readings = read_records(sys.argv[1])
    key_costs, corrections, exact, count = fit(readings, table)
    json.dump({"key_costs": key_costs, "unit_corrections": corrections, "exact": exact, "readings": count},
              open(OUTPUT_JSON, "w"), indent=1)
    write_c(table, key_costs, corrections)
    print(f"{count} readings, {exact:.4f} reproduced exactly; wrote {os.path.normpath(OUTPUT_C)}")


if __name__ == "__main__":
    main()
