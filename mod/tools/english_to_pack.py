"""Convert the English version's word files into a todmod word pack covering every list of the Japanese game.

Writes <pack>/words.tsv (main game) and <pack>/kids.tsv (Kids' Mode), columns list<TAB>difficulty<TAB>display<TAB>reading.
- Lists whose family exists in the English game get the English file of the paired family with the same number
  (spare and then reused files when there is none; same rule as transplant_tool.py).
- Quiz lists (question + valid answers) without a paired English family take English quizzes (ZE01), trimmed
  to the list's size.
- Kids' Mode word lists (S000) and normal lists without a paired family are filled with English words of about
  the same difficulty as each original slot.
- The word tables built into Tod.exe (single letters and kana, short words, drills, staff names) get English
  words, letters and symbols; staff names are romanised from the Tod.exe given (default: <pack>/../../Tod.exe).
List structure comes from word_lists.tsv next to this script (generated by gen_pack_template.py).

usage: python english_to_pack.py "The Typing of The Dead/word" "EX Installation/TODEX/dict/english" [Tod.exe]
"""
import collections
import os
import random
import re
import string
import struct
import sys

XOR_KEYS = (0x41, 0)
RECORD_BYTES = 12
TERMINATOR = 0xFFFFFFFF
FIRST_UNIT_ID = 162
UNIT_CHARACTERS = string.digits + string.ascii_uppercase + string.ascii_lowercase + "\\.,?!_[]-% '$#@.,-\"&/():*"
FAMILY_PAIRS = {"S000": "Z000", "SE00": "ZE00", "SE01": "ZE01", "SE02": "ZE02", "SE03": "ZE03",
                "SE04": "ZE04", "SE05": "ZE05", "SE06": "ZE06", "SE07": "ZE07"}
QUIZ_FAMILIES = {"SE01", "SE06"}
ENGLISH_QUIZ_FAMILY = "ZE01"
WORD_POOL_FAMILIES = {"Z000", "ZE02", "ZE03", "ZE04", "ZE05", "ZE07"}
FILLED_BY_DIFFICULTY = {("kids", "S000")}
WORD_BANK_FAMILY = "S000"
QUESTION_DIFFICULTY = 12
QUESTION_READING = "?"
MAX_SCREEN_CHARACTERS = 48  # 24 cells of half-width text ([text] half_width=1)
LIST_STRUCTURE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "word_lists.tsv")
OUTPUT_FILES = {"main": "words.tsv", "kids": "kids.tsv"}
DESCRIPTION = ("English Typing of the Dead (2001) word lists from your own copy: all stages, quizzes, Kids' Mode "
               "and the drills built into the game.\n")
HEADER = "# English version words (english_to_pack.py): list<TAB>difficulty<TAB>display<TAB>reading\n"
OLD_HEADER = "# English version words, converted by english_to_pack.py"
RANDOM_SEED = 2026

TOD_EXE_TIMESTAMP = 0x4DE72EF7
TOD_EXE_IMAGE_BASE = 0x400000
RECORD_SIZE = 0x88
READING_UNITS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "reading_units.tsv")
STAFF_TABLES = (("builtin_staff_stage", 0x504F78, 27), ("builtin_staff_kanji", 0x505DD0, 27),
                ("builtin_staff_kana", 0x506CB0, 24))
TWO_LETTER_WORDS = ("am an as at be by do go he hi if in is it me my no of oh ok on or ox so to up us we "
                    "ad ah aw ax ay eh ha ho id lo ma pa").split()
GAME_LETTERS = list("ABCDEFGHIJKLMNPQRSTUWVXYZ")
SHORT_EXTRAS = ["!!", "!?", "3D", "9AM", "DJ", "IQ", "OK", "ON"]
THREE_LETTER_WORDS = "ant bee cat dog eel fox gum hat ice jam key log mud nut owl pig".split()
DRILL = ["F", "J"] + list("1234567890") + ["'", '"', "$", "?", "!", "%", ".", ","] + list("-:;()&@/")
BUILTIN_LISTS = {
    "builtin_letters": GAME_LETTERS,
    "builtin_kana": TWO_LETTER_WORDS,
    "builtin_short_words": TWO_LETTER_WORDS + GAME_LETTERS + SHORT_EXTRAS + THREE_LETTER_WORDS,
    "builtin_drill": DRILL,
}
KANA_ROMAJI = dict(zip(
    "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"
    "がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽ",
    "a i u e o ka ki ku ke ko sa shi su se so ta chi tsu te to na ni nu ne no ha hi fu he ho ma mi mu me mo "
    "ya yu yo ra ri ru re ro wa o n ga gi gu ge go za ji zu ze zo da ji zu de do ba bi bu be bo pa pi pu pe po".split()))
SMALL_Y = {"ゃ": "a", "ゅ": "u", "ょ": "o"}
FAMILY_NAMES = sorted((
    "あさい あべ いいだ いがらし いしおか いしのだ いわなみ うえだ うちこし えざき おおおか おおかわ おおこし おおさわ "
    "おおべ おかべ おがた おづつみ かじ かなお かぶた かわうち かわかみ かわさき かわせ きおか こじま こへい さくた さたけ "
    "しのはら しみず すずき そうや たかはし たきた たぞえ たなか とくなが どうじゅん なかじま なかの ながさわ にしかわ "
    "はやし はらだ ばば ふかや ふじい ほんだ まきえ まなべ もてぎ やぶもと").split(), key=len, reverse=True)
COMPANY_NAMES = {"（かぶ）すまいるびっと": "Smilebit", "（かぶ）せがわう": "Sega Wow"}


def parse_english_file(blob):
    for key in XOR_KEYS:
        data = bytes(b ^ key for b in blob)
        try:
            words = []
            for index in range(len(data) // RECORD_BYTES):
                group, display_at, typed_at = struct.unpack_from("<III", data, index * RECORD_BYTES)
                if group == TERMINATOR:
                    break
                display = data[display_at:data.index(b"\0", display_at)].decode("latin-1")
                typed = data[typed_at:data.index(b"\0", typed_at)]
                words.append((group, display, "".join(UNIT_CHARACTERS[u - FIRST_UNIT_ID] for u in typed)))
        except (struct.error, ValueError, IndexError):
            continue
        if words and all((g & 0xFFFF) < 10000 and (g >> 16) < 16 for g, _, _ in words):
            return words
    raise ValueError("not a recognised English word file")


def file_number(name):
    return int(re.search(r"L(\d+)", name).group(1))


def read_list_structure():
    lists = []
    for line in open(LIST_STRUCTURE, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        bank, name, kind, slots = line.rstrip("\n").split("\t")
        lists.append((bank, name, kind, [int(s) for s in slots.split(",") if s]))
    return lists


def read_english_files(english_dir):
    families = collections.defaultdict(dict)
    for name in sorted(os.listdir(english_dir)):
        if re.match(r"Z[E0]\d\dL\d+\.bin$", name, re.I):
            families[name[:4].upper()][name] = parse_english_file(open(os.path.join(english_dir, name), "rb").read())
    return families


def assign(japanese_names, english_names):
    by_number = {file_number(n): n for n in english_names}
    assignment = {n: by_number[file_number(n)] for n in japanese_names if file_number(n) in by_number}
    spare = [n for n in english_names if n not in assignment.values()]
    cursor = 0
    for name in japanese_names:
        if name in assignment:
            continue
        assignment[name] = spare[cursor] if cursor < len(spare) else english_names[cursor % len(english_names)]
        cursor += 1
    return assignment


def fits(display):
    return len(display) <= MAX_SCREEN_CHARACTERS


def quiz_rows(words, slot_count):
    group, question, _ = words[0]
    rows = [(QUESTION_DIFFICULTY, question, QUESTION_READING)]
    rows += [(g, d, t) for g, d, t in words[1:] if fits(d)][: slot_count - 1]
    return rows


def file_rows(words, family, kind, slot_count):
    if kind == "quiz" and family in QUIZ_FAMILIES:
        return quiz_rows(words, slot_count) if fits(words[0][1]) else None
    rows = [(g, d, t) for g, d, t in words if fits(d)]
    if family != WORD_BANK_FAMILY and len(rows) != len(words):
        return None
    return rows or None


class WordPool:
    def __init__(self, families):
        seen, self.words = set(), []
        for family in sorted(WORD_POOL_FAMILIES):
            for words in families.get(family, {}).values():
                for group, display, typed in words:
                    if group >> 16 == 0 and fits(display) and display not in seen:
                        seen.add(display)
                        self.words.append([group, display, typed, 0, None])
        self.words.sort(key=lambda w: (w[0], w[1]))
        self.random = random.Random(RANDOM_SEED)

    def pick(self, difficulty, list_name):
        tolerance = max(2, difficulty // 8)
        for allow_repeat in (False, True):
            while True:
                candidates = [w for w in self.words if abs(w[0] - difficulty) <= tolerance and
                              (allow_repeat or w[4] != list_name)]
                if candidates:
                    least = min(w[3] for w in candidates)
                    word = self.random.choice([w for w in candidates if w[3] == least])
                    word[3] += 1
                    word[4] = list_name
                    return word[0], word[1], word[2]
                if tolerance > 10000:
                    break
                tolerance *= 2
        return self.words[0][0], self.words[0][1], self.words[0][2]


def kana_to_romaji(kana):
    out, double_next = "", False
    for i, character in enumerate(kana):
        if character == "っ":
            double_next = True
            continue
        if character in SMALL_Y:
            stem = out[:-1]
            out = stem + ("" if stem.endswith(("sh", "ch", "j")) else "y") + SMALL_Y[character]
            continue
        syllable = KANA_ROMAJI.get(character, "")
        if double_next and syllable:
            syllable = ("t" if syllable.startswith("ch") else syllable[0]) + syllable
            double_next = False
        out += syllable
    for long_vowel, short in (("ou", "o"), ("oo", "o"), ("uu", "u")):
        out = out.replace(long_vowel, short)
    return out


def english_staff_name(kana):
    if kana in COMPANY_NAMES:
        return COMPANY_NAMES[kana]
    family = next((f for f in FAMILY_NAMES if kana.startswith(f) and len(kana) > len(f)), None)
    parts = [family, kana[len(family):]] if family else [kana]
    return " ".join(kana_to_romaji(p).capitalize() for p in parts)


def read_staff_names(tod_exe):
    data = open(tod_exe, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if struct.unpack_from("<I", data, pe + 8)[0] != TOD_EXE_TIMESTAMP:
        raise ValueError("not the supported Tod.exe build")
    section_count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    sections = [struct.unpack_from("<8sIIII", data, pe + 24 + optional_size + i * 40) for i in range(section_count)]

    def file_offset(va):
        rva = va - TOD_EXE_IMAGE_BASE
        for _, virtual_size, virtual_address, raw_size, raw_offset in sections:
            if virtual_address <= rva < virtual_address + max(virtual_size, raw_size):
                return rva - virtual_address + raw_offset
        raise ValueError(f"address {va:#x} outside Tod.exe")

    unit_text = {}
    for line in open(READING_UNITS, encoding="utf-8"):
        if not line.startswith("#") and line.strip():
            text, unit = line.rstrip("\n").split("\t")
            unit_text.setdefault(int(unit), text)
    tables = {}
    for list_name, address, slots in STAFF_TABLES:
        names = []
        for slot in range(slots):
            units = struct.unpack_from("<64H", data, file_offset(address + slot * RECORD_SIZE) + 8)
            names.append("".join(unit_text.get(u, "") for u in units[:units.index(0)]))
        tables[list_name] = [english_staff_name(n) for n in names]
    return tables


def builtin_rows(tod_exe):
    lists = dict(BUILTIN_LISTS)
    try:
        lists.update(read_staff_names(tod_exe))
    except (OSError, ValueError, struct.error) as error:
        print(f"  staff names left to the game ({tod_exe}: {error})")
    rows = ["# Built into Tod.exe: letters, single-kana enemies, short words, drills, staff names\n"]
    for list_name, words in lists.items():
        rows += [f"{list_name}\t\t{word}\n" for word in words]
    return rows, len(lists)


def remove_old_list_files(pack_dir):
    removed = 0
    for folder in (pack_dir, os.path.join(pack_dir, "kids")):
        if not os.path.isdir(folder):
            continue
        for name in os.listdir(folder):
            path = os.path.join(folder, name)
            if name.endswith(".txt") and open(path, encoding="utf-8").readline().startswith(OLD_HEADER):
                os.remove(path)
                removed += 1
    return removed


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    english_dir, pack_dir = sys.argv[1:3]
    tod_exe = sys.argv[3] if len(sys.argv) == 4 else os.path.join(pack_dir, "..", "..", "Tod.exe")
    families = read_english_files(english_dir)
    pool = WordPool(families)
    quizzes = [w for _, w in sorted(families[ENGLISH_QUIZ_FAMILY].items()) if fits(w[0][1])]
    lists = read_list_structure()
    assignments = {}
    for bank in OUTPUT_FILES:
        by_family = collections.defaultdict(list)
        for list_bank, name, _, _ in lists:
            if list_bank == bank:
                by_family[name[:4]].append(name)
        for family, names in by_family.items():
            english_family = FAMILY_PAIRS.get(family)
            if english_family in families:
                assignments.update({(bank, n): e for n, e in assign(sorted(names, key=file_number),
                                                                     sorted(families[english_family])).items()})
    os.makedirs(pack_dir, exist_ok=True)
    report = collections.Counter()
    quiz_cursor = 0
    for bank, file_name in OUTPUT_FILES.items():
        out = [HEADER]
        for list_bank, name, kind, slots in lists:
            if list_bank != bank:
                continue
            family = name[:4]
            rows, how = None, None
            english_name = assignments.get((bank, name))
            if english_name and (bank, family) not in FILLED_BY_DIFFICULTY:
                rows = file_rows(families[FAMILY_PAIRS[family]][english_name], family, kind, len(slots))
                how = "English list"
            if rows is None and kind == "quiz":
                rows = quiz_rows(quizzes[quiz_cursor % len(quizzes)], len(slots))
                quiz_cursor += 1
                how = "English quiz"
            if rows is None and kind == "normal":
                rows = [pool.pick(d, f"{bank}/{name}") for d in slots]
                how = "English words by difficulty"
            if rows is None:
                report[(bank, "left to the game")] += 1
                continue
            report[(bank, how)] += 1
            out += [f"{name}\t{g}\t{d}\t{t}\n" for g, d, t in rows]
        if bank == "main":
            rows, builtin_count = builtin_rows(tod_exe)
            out += rows
            report[(bank, "English words for the tables built into Tod.exe")] += builtin_count
        with open(os.path.join(pack_dir, file_name), "w", encoding="utf-8", newline="\n") as handle:
            handle.writelines(out)
    for (bank, how), count in sorted(report.items()):
        print(f"  {bank}: {count} lists {how}" if how == "left to the game" else f"  {bank}: {count} lists from {how}")
    with open(os.path.join(pack_dir, "description.txt"), "w", encoding="utf-8", newline="\r\n") as handle:
        handle.write(DESCRIPTION)
    removed = remove_old_list_files(pack_dir)
    print(f"wrote {', '.join(OUTPUT_FILES.values())} to {pack_dir}" + (f"; removed {removed} old list files" if removed else ""))


if __name__ == "__main__":
    main()
